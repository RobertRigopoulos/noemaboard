interface Props {
  /** Icon id, or null/unknown for the default board glyph. */
  icon: string | null | undefined
  size?: number
  strokeWidth?: number
  className?: string
  /** Render nothing (instead of the default glyph) when the board has no icon. */
  noFallback?: boolean
}

export function BoardIcon({ icon, size = 20, strokeWidth = 1.75, className, noFallback }: Props) {
  const Icon = isBoardIconId(icon) ? ICONS[icon] : undefined
  if (!Icon && noFallback) return null
  const C = Icon ?? LayoutGrid
  return <C size={size} strokeWidth={strokeWidth} className={className} aria-hidden />
}

